#!/usr/bin/env python3
"""Generate .github/workflows/mz-linux-build.yml (N chained stages). Usage: python ci/linux/gen_workflow.py [N] [BUDGET_MIN]"""
import sys
from pathlib import Path

N = int(sys.argv[1]) if len(sys.argv) > 1 else 8
BUDGET = int(sys.argv[2]) if len(sys.argv) > 2 else 300
ROOT = Path(__file__).resolve().parents[2]

HEAD = '''# MZ kernel, Linux x64 (headless servers / agents), built in stages on free runners.
# Same scheme as mz-win-build: a stage that runs out of time packs the work tree
# (depot_tools + chromium/src incl. out/Default, no .git) into artifact "mz-tree";
# the next stage restores it and ninja continues. The finishing stage uploads
# mz-browser-kernel-<ver>-linux-x64.zip (artifact "mz-kernel-linux").
# Generated by ci/linux/gen_workflow.py, edit that file instead.
name: mz-linux-build

on:
  push:
    branches: ['ci/**']
    paths: ['.github/workflows/mz-linux-build.yml', '.github/actions/mz-linux-setup/**', 'ci/linux/**']
  workflow_dispatch:
    inputs:
      resume_run_id:
        description: 'Resume from the mz-tree artifact of this earlier run (empty = full sync)'
        required: false
        default: ''

permissions:
  contents: read
  actions: read

concurrency:
  group: mz-linux-build-${{ github.ref }}
  cancel-in-progress: false

env:
  CHROMIUM_TAG: '158.0.8127.37'
  PYTHONUNBUFFERED: '1'
  PYTHONUTF8: '1'

jobs:
'''

RESTORE = '''      - name: Restore work tree
        run: |
          cd "$MZ_WORK"
          zstd -d -T0 --stdout tree.tar.zst | tar -x
          rm -f tree.tar.zst
          df -h "$MZ_WORK"
'''


def finish_steps() -> str:
    return '''      - name: Package kernel
        if: steps.build.outputs.finished == 'true'
        run: python ci/linux/stage.py package
      - name: Upload kernel
        if: steps.build.outputs.finished == 'true'
        uses: actions/upload-artifact@v4
        with:
          name: mz-kernel-linux
          path: |
            ${{ env.MZ_WORK }}/dist/*.zip
            ${{ env.MZ_WORK }}/dist/SHA256SUMS.txt
          compression-level: 0
          retention-days: 14
      - name: Pack work tree for the next stage
        if: steps.build.outputs.finished == 'false' || steps.build.outputs.finished == 'failed'
        run: |
          cd "$MZ_WORK"
          tar --exclude=.git --exclude='*.git' -cf - depot_tools chromium | zstd -1 -T0 -q -o tree.tar.zst
          ls -l tree.tar.zst
      - name: Upload work tree
        if: steps.build.outputs.finished == 'false' || steps.build.outputs.finished == 'failed'
        uses: actions/upload-artifact@v4
        with:
          name: mz-tree
          path: ${{ env.MZ_WORK }}/tree.tar.zst
          compression-level: 0
          retention-days: 3
          overwrite: true
      - name: Fail on ninja errors (tree kept for resume_run_id)
        if: steps.build.outputs.finished == 'failed'
        run: |
          echo "ninja failed; fix, push, then re-run with resume_run_id=${{ github.run_id }}"
          exit 1
'''


def job_head(i: int) -> str:
    need = '' if i == 1 else f"    needs: stage-{i-1}\n    if: needs.stage-{i-1}.outputs.finished == 'false'\n"
    return (f"  stage-{i}:\n{need}"
            "    runs-on: ubuntu-24.04\n"
            "    timeout-minutes: 355\n"
            "    defaults: { run: { shell: bash } }\n"
            "    outputs:\n"
            "      finished: ${{ steps.build.outputs.finished }}\n"
            "    steps:\n"
            "      - uses: actions/checkout@v4\n"
            "      - uses: ./.github/actions/mz-linux-setup\n")


def main() -> None:
    y = HEAD
    y += job_head(1) + '''      - name: Fetch Chromium ${{ env.CHROMIUM_TAG }} (gclient, no history)
        if: inputs.resume_run_id == ''
        run: python ci/linux/stage.py sync
      - name: Apply MZ overlays and gn gen
        if: inputs.resume_run_id == ''
        run: python ci/linux/stage.py prepare
      - name: Download work tree of run ${{ inputs.resume_run_id }}
        if: inputs.resume_run_id != ''
        uses: actions/download-artifact@v4
        with:
          name: mz-tree
          path: ${{ env.MZ_WORK }}
          run-id: ${{ inputs.resume_run_id }}
          github-token: ${{ github.token }}
'''
    y += RESTORE.replace("      - name: Restore work tree\n",
                         "      - name: Restore work tree\n        if: inputs.resume_run_id != ''\n")
    y += '''      - name: Apply ci/linux/fixups to the restored tree
        if: inputs.resume_run_id != ''
        run: python ci/linux/stage.py fixups
'''
    y += f'''      - name: Build (ninja, time-boxed)
        id: build
        run: python ci/linux/stage.py build --budget-minutes {BUDGET}
''' + finish_steps()
    for i in range(2, N + 1):
        y += job_head(i) + '''      - uses: actions/download-artifact@v4
        with:
          name: mz-tree
          path: ${{ env.MZ_WORK }}
''' + RESTORE
        y += f'''      - name: Build (ninja, time-boxed)
        id: build
        run: python ci/linux/stage.py build --budget-minutes {BUDGET}
''' + finish_steps()
    (ROOT / '.github' / 'workflows' / 'mz-linux-build.yml').write_text(y, encoding='utf-8')


if __name__ == '__main__':
    main()
