#!/usr/bin/env python3
"""Generate .github/workflows/mz-win-build.yml (N chained stages). Usage: python ci/win/gen_workflow.py [N] [BUDGET_MIN]"""
import sys
from pathlib import Path

N = int(sys.argv[1]) if len(sys.argv) > 1 else 10
BUDGET = int(sys.argv[2]) if len(sys.argv) > 2 else 285
ROOT = Path(__file__).resolve().parents[2]

HEAD = '''# MZ kernel, Windows x64, built in stages on free GitHub-hosted runners.
# Each stage is one job (< 6 h). A stage that runs out of time packs the whole
# work tree (depot_tools + chromium/src incl. out/Default) into the artifact
# "mz-tree"; the next stage restores it to the same path and ninja continues.
# The stage that finishes packages mz-browser-kernel-<ver>-win-x64.zip (artifact "mz-kernel").
# Generated by ci/win/gen_workflow.py, edit that file instead.
name: mz-win-build

on:
  push:
    branches: ['ci/**']
    paths: ['.github/workflows/mz-win-build.yml', '.github/actions/mz-win-setup/**', 'ci/win/**']
  workflow_dispatch:
    inputs:
      resume_run_id:
        description: 'Resume from the mz-tree artifact of this earlier run (empty = full sync)'
        required: false
        default: ''

permissions:
  contents: read
  actions: read

concurrency:
  group: mz-win-build-${{ github.ref }}
  cancel-in-progress: false

env:
  CHROMIUM_TAG: '158.0.8127.37'
  PYTHONUNBUFFERED: '1'
  PYTHONUTF8: '1'
  DEPOT_TOOLS_WIN_TOOLCHAIN: '0'

jobs:
'''


def finish_steps() -> str:
    return '''      - name: Package kernel zip
        if: steps.build.outputs.finished == 'true'
        run: python ci/win/stage.py package
      - name: Upload kernel zip
        if: steps.build.outputs.finished == 'true'
        uses: actions/upload-artifact@v4
        with:
          name: mz-kernel
          path: |
            ${{ env.MZ_WORK }}/dist/*.zip
            ${{ env.MZ_WORK }}/dist/SHA256SUMS.txt
          compression-level: 0
          retention-days: 14
      - name: Pack work tree for the next stage
        if: steps.build.outputs.finished == 'false' || steps.build.outputs.finished == 'failed'
        run: |
          Set-Location $env:MZ_WORK
          # 7z exit code 1 = warnings only (dangling symlinks such as node_modules/.bin, nearby includes); >= 2 is a real error
          7z a -t7z -m0=lzma2 -mx=1 -mmt=on -mtc=on "-xr!.git" tree.7z depot_tools chromium | Select-Object -Last 5
          $rc = $LASTEXITCODE
          Get-Item tree.7z | Format-List Name, Length
          if ($rc -gt 1) { throw "7z failed with exit code $rc" }
          $global:LASTEXITCODE = 0
      - name: Upload work tree
        if: steps.build.outputs.finished == 'false' || steps.build.outputs.finished == 'failed'
        uses: actions/upload-artifact@v4
        with:
          name: mz-tree
          path: ${{ env.MZ_WORK }}/tree.7z
          compression-level: 0
          retention-days: 3
          overwrite: true
      - name: Fail on ninja errors (tree kept for resume_run_id)
        if: steps.build.outputs.finished == 'failed'
        run: throw "ninja failed; fix, push, then re-run with resume_run_id=${{ github.run_id }}"
'''


def job_head(i: int) -> str:
    need = '' if i == 1 else f"    needs: stage-{i-1}\n    if: needs.stage-{i-1}.outputs.finished == 'false'\n"
    return (f"  stage-{i}:\n{need}"
            "    runs-on: windows-2022\n"
            "    timeout-minutes: 355\n"
            "    defaults: { run: { shell: pwsh } }\n"
            "    outputs:\n"
            "      finished: ${{ steps.build.outputs.finished }}\n"
            "    steps:\n"
            "      - uses: actions/checkout@v4\n"
            "      - uses: ./.github/actions/mz-win-setup\n")


def main() -> None:
    y = HEAD
    y += job_head(1) + '''      - name: Fetch Chromium ${{ env.CHROMIUM_TAG }} (gclient, no history)
        if: inputs.resume_run_id == ''
        run: python ci/win/stage.py sync
      - name: Apply MZ overlays and gn gen
        if: inputs.resume_run_id == ''
        run: python ci/win/stage.py prepare
      - name: Download work tree of run ${{ inputs.resume_run_id }}
        if: inputs.resume_run_id != ''
        uses: actions/download-artifact@v4
        with:
          name: mz-tree
          path: ${{ env.MZ_WORK }}
          run-id: ${{ inputs.resume_run_id }}
          github-token: ${{ github.token }}
      - name: Restore work tree
        if: inputs.resume_run_id != ''
        run: |
          Set-Location $env:MZ_WORK
          7z x -y -mmt=on tree.7z | Select-Object -Last 3
          $rc = $LASTEXITCODE
          if ($rc -gt 1) { throw "7z failed with exit code $rc" }
          Remove-Item tree.7z
          $global:LASTEXITCODE = 0
      - name: Apply ci/win/fixups to the restored tree
        if: inputs.resume_run_id != ''
        run: python ci/win/stage.py fixups
'''
    y += f'''      - name: Build (ninja, time-boxed)
        id: build
        run: python ci/win/stage.py build --budget-minutes {BUDGET}
''' + finish_steps()
    for i in range(2, N + 1):
        y += job_head(i) + '''      - uses: actions/download-artifact@v4
        with:
          name: mz-tree
          path: ${{ env.MZ_WORK }}
      - name: Restore work tree
        run: |
          Set-Location $env:MZ_WORK
          7z x -y -mmt=on tree.7z | Select-Object -Last 3
          $rc = $LASTEXITCODE
          if ($rc -gt 1) { throw "7z failed with exit code $rc" }
          Remove-Item tree.7z
          $global:LASTEXITCODE = 0
'''
        y += f'''      - name: Build (ninja, time-boxed)
        id: build
        run: python ci/win/stage.py build --budget-minutes {BUDGET}
''' + finish_steps()
    (ROOT / '.github' / 'workflows' / 'mz-win-build.yml').write_text(y, encoding='utf-8')


if __name__ == '__main__':
    main()
